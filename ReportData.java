 class ReportData {

    private String productCode;

    private String productName;

    private String productCategory;

    private String productWarranty;

    private double productPrice;

    private int productLevel;

    private String productSupplier;

    public String getProductCode() { return productCode; }

    public void setProductCode(String productCode) { this.productCode = productCode; }

    public String getProductName() { return productName; }

    public void setProductName(String productName) { this.productName = productName; }

    public String getProductCategory() { return productCategory; }

    public void setProductCategory(String productCategory) { this.productCategory = productCategory; }

    public String getProductWarranty() { return productWarranty; }

    public void setProductWarranty(String productWarranty) { this.productWarranty = productWarranty; }

    public double getProductPrice() { return productPrice; }

    public void setProductPrice(double productPrice) { this.productPrice = productPrice; }

    public int getProductLevel() { return productLevel; }

    public void setProductLevel(int productLevel) { this.productLevel = productLevel; }

    public String getProductSupplier() { return productSupplier; }

    public void setProductSupplier(String productSupplier) { this.productSupplier = productSupplier; }

}
 