 class products {

    String productCode;

    String productName;

    String productCategory;

    String productWarranty;

    double productPrice;

    int productLevel;

    String productSupplier;

    public products(String code, String name, String category, String warranty, double price, int level, String supplier) {

        this.productCode = code;

        this.productName = name;

        this.productCategory = category;

        this.productWarranty = warranty;

        this.productPrice = price;

        this.productLevel = level;

        this.productSupplier = supplier;

    }

}
 